// supportedSchemaVersion is the only snapshot shape the running service
// understands today.
const supportedSchemaVersion = 1

var (
	hex64Pattern   = regexp.MustCompile(`^[0-9a-f]{64}$`)
	entityPatterns = []struct {
		prefix  string
		pattern *regexp.Regexp
	}{
		{"pln_", regexp.MustCompile(`^pln_[0-9a-f]{20}$`)},
		{"rev_", regexp.MustCompile(`^rev_[0-9a-f]{20}$`)},
		{"nod_", regexp.MustCompile(`^nod_[0-9a-f]{20}$`)},
		{"lse_", regexp.MustCompile(`^lse_[0-9a-f]{20}$`)},
		{"grp_", regexp.MustCompile(`^grp_[0-9a-f]{20}$`)},
		{"prb_", regexp.MustCompile(`^prb_[0-9a-f]{20}$`)},
		{"asm_", regexp.MustCompile(`^asm_[0-9a-f]{20}$`)},
		{"aud_", regexp.MustCompile(`^aud_[0-9a-f]{20}$`)},
	}
	knownAuditEntities = map[string]struct{}{
		"plan":        {},
		"revision":    {},
		"node":        {},
		"lease":       {},
		"lease_group": {},
		"probe":       {},
		"assessment":  {},
	}
)

// Validate performs the four offline verification stages against a decoded,
// normalized candidate snapshot: format, entity references, idempotency
// indexes and recomputed summaries. It never touches the filesystem or the
// network and never consults a running service.
func Validate(state *domain.State) []Finding {
	ctx := &validationContext{
		state:      state,
		collector:  &findingCollector{},
		nodeLeases: make(map[string][]string),
	}
	if entityCount(state) == 0 {
		ctx.format("empty_snapshot", "snapshot contains no entities; nothing to recover", "")
	}
	ctx.validatePlans()
	ctx.validateRevisions()
	ctx.validateNodes()
	ctx.validateLeases()
	ctx.validateLeaseGroups()
	ctx.validateProbes()
	ctx.validateAssessments()
	ctx.validateAudit()
	ctx.validateIndexes()
	ctx.validateGlobalCoherence()
	sort.SliceStable(ctx.collector.items, func(i, j int) bool {
		if ctx.collector.items[i].Category != ctx.collector.items[j].Category {
			return ctx.collector.items[i].Category < ctx.collector.items[j].Category
		}
		if ctx.collector.items[i].Ref != ctx.collector.items[j].Ref {
			return ctx.collector.items[i].Ref < ctx.collector.items[j].Ref
		}
		return ctx.collector.items[i].Code < ctx.collector.items[j].Code
	})
	return ctx.collector.items
}

type validationContext struct {
	state      *domain.State
	collector  *findingCollector
	nodeLeases map[string][]string
}

func (c *validationContext) format(code, message, ref string) {
	c.collector.format(code, message, ref)
}

func (c *validationContext) reference(code, message, ref string) {
	c.collector.reference(code, message, ref)
}

func (c *validationContext) index(code, message, ref string) {
	c.collector.index(code, message, ref)
}

func (c *validationContext) summary(code, message, ref string) {
	c.collector.summary(code, message, ref)
}

func (c *validationContext) validateID(id, prefix string) bool {
	for _, candidate := range entityPatterns {
		if candidate.prefix != prefix {
			continue
		}
		return candidate.pattern.MatchString(id)
	}
	return false
}

func (c *validationContext) validatePlans() {
	state := c.state
	if state.SchemaVersion != supportedSchemaVersion {
		c.format("unsupported_schema_version", "schema_version must be 1", "")
	}
	expectedVersion := func(plan domain.RolloutPlan, revisionCount, assessmentCount int) uint64 {
		version := uint64(1 + revisionCount + assessmentCount)
		if plan.State == domain.PlanActive || plan.State == domain.PlanCompleted {
			version++
		}
		if plan.State == domain.PlanCompleted {
			version++
		}
		return version
	}
	for key, plan := range state.Plans {
		if key != plan.ID {
			c.format("map_key_mismatch", "plans map key does not match plan id", key)
		}
		if !c.validateID(plan.ID, "pln_") {
			c.format("invalid_id", "plan id must be generated by the service", key)
		}
		if err := validateCanonical(plan.Zone); err != nil {
			c.format("invalid_zone", err.Error(), plan.ID)
		}
		switch plan.State {
		case domain.PlanDraft, domain.PlanActive, domain.PlanCompleted:
		default:
			c.format("invalid_plan_state", "plan state must be draft, active or completed", plan.ID)
		}
		if plan.MinimumSuccessRatio < 0 || plan.MinimumSuccessRatio > 1 {
			c.format("invalid_ratio", "minimum_success_ratio must be between 0 and 1", plan.ID)
		}
		if plan.MaximumLatencyMS < 1 || plan.MaximumLatencyMS > 600000 {
			c.format("invalid_latency", "maximum_latency_ms must be between 1 and 600000", plan.ID)
		}
		if plan.ExpectedNodes < 1 || plan.ExpectedNodes > 500 {
			c.format("invalid_expected_nodes", "expected_nodes must be between 1 and 500", plan.ID)
		}
		if plan.Version < 1 {
			c.format("invalid_version", "plan version must be at least 1", plan.ID)
		}
		if plan.CreatedAt.IsZero() {
			c.format("missing_timestamp", "created_at is required", plan.ID)
		}
		switch plan.State {
		case domain.PlanActive:
			if plan.ActivatedAt == nil {
				c.format("missing_timestamp", "active plan must record activated_at", plan.ID)
			}
			if plan.CompletedAt != nil {
				c.format("invalid_transition", "active plan must not record completed_at", plan.ID)
			}
		case domain.PlanCompleted:
			if plan.ActivatedAt == nil {
				c.format("missing_timestamp", "completed plan must record activated_at", plan.ID)
			}
			if plan.CompletedAt == nil {
				c.format("missing_timestamp", "completed plan must record completed_at", plan.ID)
			}
		case domain.PlanDraft:
			if plan.ActivatedAt != nil || plan.CompletedAt != nil {
				c.format("invalid_transition", "draft plan must not record activation or completion times", plan.ID)
			}
		}

		revisionCount := 0
		var maxSerial uint32
		var latestRevisionID string
		revisionSerials := make(map[uint32]struct{})
		for _, revision := range state.Revisions {
			if revision.PlanID != plan.ID {
				continue
			}
			revisionCount++
			revisionSerials[revision.Serial] = struct{}{}
			if revision.Serial >= maxSerial {
				maxSerial = revision.Serial
				latestRevisionID = revision.ID
			}
		}
		if revisionCount == 0 && plan.State != domain.PlanDraft {
			c.reference("plan_without_revision", "active or completed plan must contain at least one revision", plan.ID)
		}
		if revisionCount == 0 && plan.LatestRevisionID != "" {
			c.reference("dangling_revision_pointer", "latest_revision_id points at a missing revision", plan.ID)
		}
		if revisionCount > 0 {
			if plan.LatestRevisionID == "" {
				c.summary("latest_revision_pointer", "plan with revisions must record latest_revision_id", plan.ID)
			} else if plan.LatestRevisionID != latestRevisionID {
				c.summary("latest_revision_pointer", "latest_revision_id must point at the revision with the highest serial", plan.ID)
			}
		}
		if len(revisionSerials) != revisionCount {
			c.format("duplicate_revision_serial", "revision serials must be unique within a plan", plan.ID)
		}
		assessmentCount := 0
		var latestAssessmentAt time.Time
		for _, assessment := range state.Assessments {
			if assessment.PlanID != plan.ID {
				continue
			}
			assessmentCount++
			if latestAssessmentAt.IsZero() || assessment.CreatedAt.After(latestAssessmentAt) {
				latestAssessmentAt = assessment.CreatedAt
			}
		}
		if assessmentCount > 0 {
			latest, ok := state.Assessments[plan.LatestAssessmentID]
			if plan.LatestAssessmentID == "" || !ok || latest.PlanID != plan.ID {
				c.summary("latest_assessment_pointer", "plan with assessments must record a present latest_assessment_id", plan.ID)
			} else if !latest.CreatedAt.Equal(latestAssessmentAt) {
				c.summary("latest_assessment_pointer", "latest_assessment_id must point at the most recently created assessment", plan.ID)
			}
		} else if plan.LatestAssessmentID != "" {
			c.reference("dangling_assessment_pointer", "latest_assessment_id points at a missing assessment", plan.ID)
		}
		if want := expectedVersion(plan, revisionCount, assessmentCount); plan.Version != want {
			c.summary("plan_version", "plan version does not match its revision and assessment history", plan.ID)
		}
	}

	for revisionID, revision := range state.Revisions {
		if _, ok := state.Plans[revision.PlanID]; !ok {
			c.reference("revision_without_plan", "revision references a missing plan", revisionID)
		}
	}
}

func (c *validationContext) validateRevisions() {
	state := c.state
	for key, revision := range state.Revisions {
		if key != revision.ID {
			c.format("map_key_mismatch", "revisions map key does not match revision id", key)
		}
		if !c.validateID(revision.ID, "rev_") {
			c.format("invalid_id", "revision id must be generated by the service", key)
		}
		if revision.Serial == 0 {
			c.format("invalid_serial", "revision serial must be greater than zero", revision.ID)
		}
		if err := validateCanonical(revision.Authority); err != nil {
			c.format("invalid_authority", err.Error(), revision.ID)
		}
		if revision.CreatedAt.IsZero() {
			c.format("missing_timestamp", "created_at is required", revision.ID)
		}
		if revision.EntryCount != len(revision.Entries) {
			c.summary("entry_count", "entry_count must equal the number of entries", revision.ID)
		}
		if len(revision.Entries) < 1 || len(revision.Entries) > domain.MaxEntries {
			c.format("invalid_entries", "entries must contain between 1 and 500 items", revision.ID)
		}
		seen := make(map[domain.ZoneEntry]struct{}, len(revision.Entries))
		var previous *domain.ZoneEntry
		for _, entry := range revision.Entries {
			if err := validateCanonical(entry.Owner); err != nil {
				c.format("invalid_owner", err.Error(), revision.ID)
			}
			switch entry.Type {
			case domain.EntryA:
				ip := net.ParseIP(entry.Value)
				if ip == nil || ip.To4() == nil || ip.To4().String() != entry.Value {
					c.format("invalid_entry_value", "A entry value must be a canonical IPv4 address", revision.ID)
				}
			case domain.EntryAAAA:
				ip := net.ParseIP(entry.Value)
				if ip == nil || ip.To4() != nil || ip.String() != entry.Value {
					c.format("invalid_entry_value", "AAAA entry value must be a canonical IPv6 address", revision.ID)
				}
			case domain.EntryCNAME:
				if err := validateCanonical(entry.Value); err != nil {
					c.format("invalid_entry_value", err.Error(), revision.ID)
				}
			default:
				c.format("invalid_entry_type", "entry type must be A, AAAA or CNAME", revision.ID)
			}
			if _, duplicate := seen[entry]; duplicate {
				c.format("duplicate_entry", "entries must be unique", revision.ID)
			}
			seen[entry] = struct{}{}
			if previous != nil && !entryLess(*previous, entry) {
				c.format("entries_not_sorted", "entries must be sorted by owner, type and value", revision.ID)
			}
			entryCopy := entry
			previous = &entryCopy
		}
		if plan, ok := state.Plans[revision.PlanID]; ok && revision.CreatedAt.Before(plan.CreatedAt) {
			c.format("timestamp_order", "revision cannot predate its plan", revision.ID)
		}
	}

	// Serials must strictly increase for each plan.
	byPlan := make(map[string][]domain.ZoneRevision)
	for _, revision := range state.Revisions {
		byPlan[revision.PlanID] = append(byPlan[revision.PlanID], revision)
	}
	for planID, revisions := range byPlan {
		sort.Slice(revisions, func(i, j int) bool {
			return revisions[i].CreatedAt.Before(revisions[j].CreatedAt)
		})
		for i := 1; i < len(revisions); i++ {
			if revisions[i].Serial <= revisions[i-1].Serial {
				c.format("serial_not_increasing", "revision serials must strictly increase over time", planID)
				break
			}
		}
	}
}

func entryLess(a, b domain.ZoneEntry) bool {
	if a.Owner != b.Owner {
		return a.Owner < b.Owner
	}
	if a.Type != b.Type {
		return a.Type < b.Type
	}
	return a.Value < b.Value
}

func (c *validationContext) validateNodes() {
	state := c.state
	names := make(map[string]string)
	for key, node := range state.Nodes {
		if key != node.ID {
			c.format("map_key_mismatch", "nodes map key does not match node id", key)
		}
		if !c.validateID(node.ID, "nod_") {
			c.format("invalid_id", "node id must be generated by the service", key)
		}
		if err := validateCanonical(node.NodeName); err != nil {
			c.format("invalid_node_name", err.Error(), node.ID)
		}
		region := strings.TrimSpace(strings.ToLower(node.Region))
		if count := utf8.RuneCountInString(region); count < 2 || count > domain.MaxRegionRunes || region != node.Region {
			c.format("invalid_region", "region must be 2 to 48 lowercase characters", node.ID)
		}
		switch node.State {
		case domain.NodeReady, domain.NodeLeased, domain.NodeQuarantined:
		default:
			c.format("invalid_node_state", "node state must be ready, leased or quarantined", node.ID)
		}
		if node.Version < 1 {
			c.format("invalid_version", "node version must be at least 1", node.ID)
		}
		if node.CreatedAt.IsZero() || node.UpdatedAt.IsZero() {
			c.format("missing_timestamp", "created_at and updated_at are required", node.ID)
		} else if node.UpdatedAt.Before(node.CreatedAt) {
			c.format("timestamp_order", "updated_at cannot predate created_at", node.ID)
		}
		if owner, duplicate := names[node.NodeName]; duplicate {
			c.format("duplicate_node_name", "node_name must be unique", node.ID+" / "+owner)
		} else {
			names[node.NodeName] = node.ID
		}
	}
}

func (c *validationContext) validateLeases() {
	state := c.state
	for key, lease := range state.Leases {
		if key != lease.ID {
			c.format("map_key_mismatch", "leases map key does not match lease id", key)
		}
		if !c.validateID(lease.ID, "lse_") {
			c.format("invalid_id", "lease id must be generated by the service", key)
		}
		plan, ok := state.Plans[lease.PlanID]
		if !ok {
			c.reference("lease_without_plan", "lease references a missing plan", lease.ID)
		} else if plan.State == domain.PlanDraft {
			c.format("lease_in_draft_plan", "leases can exist only on active or completed plans", lease.ID)
		}
		node, nodeOK := state.Nodes[lease.NodeID]
		if !nodeOK {
			c.reference("lease_without_node", "lease references a missing node", lease.ID)
		}
		c.nodeLeases[lease.NodeID] = append(c.nodeLeases[lease.NodeID], lease.ID)
		if !c.validateID(lease.AllocationID, "grp_") {
			c.format("invalid_id", "lease allocation_id must reference a lease group", lease.ID)
		}
		group, groupOK := state.LeaseGroups[lease.AllocationID]
		if !groupOK {
			c.reference("lease_without_group", "lease references a missing lease group", lease.ID)
		} else if group.PlanID != lease.PlanID {
			c.reference("lease_group_plan_mismatch", "lease group belongs to another plan", lease.ID)
		}
		switch lease.State {
		case domain.LeaseClaimed, domain.LeaseReported, domain.LeaseReleased, domain.LeaseExpired:
		default:
			c.format("invalid_lease_state", "lease state must be claimed, reported, released or expired", lease.ID)
		}
		if lease.ClaimedAt.IsZero() || lease.ExpiresAt.IsZero() {
			c.format("missing_timestamp", "claimed_at and expires_at are required", lease.ID)
		} else if !lease.ExpiresAt.After(lease.ClaimedAt) {
			c.format("invalid_lease_window", "expires_at must be after claimed_at", lease.ID)
		}
		switch lease.State {
		case domain.LeaseReleased, domain.LeaseExpired:
			if lease.FinishedAt == nil {
				c.format("missing_timestamp", "finished lease must record finished_at", lease.ID)
			}
		case domain.LeaseReported:
			if lease.FinishedAt == nil {
				c.format("missing_timestamp", "reported lease must record finished_at", lease.ID)
			}
			if lease.ProbeID == "" {
				c.format("missing_probe_pointer", "reported lease must record its probe id", lease.ID)
			}
		case domain.LeaseClaimed:
			if lease.ProbeID != "" {
				c.format("unexpected_probe_pointer", "claimed lease must not record a probe id", lease.ID)
			}
		}
		if lease.ProbeID != "" {
			if !c.validateID(lease.ProbeID, "prb_") {
				c.format("invalid_id", "lease probe_id must reference a probe", lease.ID)
			} else if probe, ok := state.Probes[lease.ProbeID]; !ok {
				c.reference("lease_without_probe", "lease references a missing probe", lease.ID)
			} else {
				if probe.LeaseID != lease.ID {
					c.reference("probe_lease_mismatch", "referenced probe belongs to another lease", lease.ID)
				}
				if nodeOK && probe.NodeID != node.ID {
					c.reference("probe_node_mismatch", "referenced probe belongs to another node", lease.ID)
				}
				if probe.PlanID != lease.PlanID {
					c.reference("probe_plan_mismatch", "referenced probe belongs to another plan", lease.ID)
				}
			}
		}
		if groupOK && lease.ClaimedAt.Before(group.CreatedAt) {
			c.format("timestamp_order", "lease cannot predate its allocation group", lease.ID)
		}
	}

	// Node/lease lifecycle coherence.
	for nodeID, leaseIDs := range c.nodeLeases {
		node, nodeOK := state.Nodes[nodeID]
		activeClaims := 0
		for _, leaseID := range leaseIDs {
			if state.Leases[leaseID].State == domain.LeaseClaimed {
				activeClaims++
			}
		}
		if activeClaims > 1 {
			c.reference("node_double_leased", "node has more than one claimed lease", nodeID)
			continue
		}
		if !nodeOK {
			continue
		}
		switch {
		case activeClaims == 1 && node.State != domain.NodeLeased:
			c.summary("node_state", "node with a claimed lease must be in leased state", nodeID)
		case activeClaims == 0 && node.State == domain.NodeLeased:
			c.summary("node_state", "leased node has no claimed lease", nodeID)
		}
	}
}

func (c *validationContext) validateLeaseGroups() {
	state := c.state
	for key, group := range state.LeaseGroups {
		if key != group.ID {
			c.format("map_key_mismatch", "lease_groups map key does not match group id", key)
		}
		if !c.validateID(group.ID, "grp_") {
			c.format("invalid_id", "lease group id must be generated by the service", key)
		}
		if _, ok := state.Plans[group.PlanID]; !ok {
			c.reference("group_without_plan", "lease group references a missing plan", group.ID)
		}
		if !validRequestKey(group.RequestKey) {
			c.format("invalid_request_key", "request_key must contain 8 to 64 letters, digits, hyphens or underscores", group.ID)
		}
		if !hex64Pattern.MatchString(group.RequestFingerprint) {
			c.format("invalid_fingerprint", "request_fingerprint must be a 64 character hex sha256 digest", group.ID)
		}
		if count := utf8.RuneCountInString(group.Region); count > domain.MaxRegionRunes {
			c.format("invalid_region", "region must be at most 48 characters", group.ID)
		}
		if group.CreatedAt.IsZero() {
			c.format("missing_timestamp", "created_at is required", group.ID)
		}
		if len(group.LeaseIDs) == 0 {
			c.format("empty_group", "lease group must contain at least one lease", group.ID)
		}
		expiry := time.Time{}
		for index, leaseID := range group.LeaseIDs {
			lease, ok := state.Leases[leaseID]
			if !ok {
				c.reference("group_without_lease", "lease group references a missing lease", group.ID)
				continue
			}
			if lease.AllocationID != group.ID {
				c.reference("group_lease_backreference", "grouped lease does not point back at the group", group.ID)
			}
			if index == 0 {
				expiry = lease.ExpiresAt
			} else if !lease.ExpiresAt.Equal(expiry) {
				c.summary("group_expiry", "all leases of a group must share the same expires_at", group.ID)
			}
		}
	}
}

func (c *validationContext) validateProbes() {
	state := c.state
	leaseProbes := make(map[string]string)
	for key, probe := range state.Probes {
		if key != probe.ID {
			c.format("map_key_mismatch", "probes map key does not match probe id", key)
		}
		if !c.validateID(probe.ID, "prb_") {
			c.format("invalid_id", "probe id must be generated by the service", key)
		}
		if !validRequestKey(probe.RequestKey) {
			c.format("invalid_request_key", "request_key must contain 8 to 64 letters, digits, hyphens or underscores", probe.ID)
		}
		if !hex64Pattern.MatchString(probe.PayloadFingerprint) {
			c.format("invalid_fingerprint", "payload_fingerprint must be a 64 character hex sha256 digest", probe.ID)
		}
		if probe.LatencyMS < 0 || probe.LatencyMS > 600000 {
			c.format("invalid_latency", "latency_ms must be between 0 and 600000", probe.ID)
		}
		if probe.ObservedAt.IsZero() || probe.StoredAt.IsZero() {
			c.format("missing_timestamp", "observed_at and stored_at are required", probe.ID)
		}
		if _, ok := state.Plans[probe.PlanID]; !ok {
			c.reference("probe_without_plan", "probe references a missing plan", probe.ID)
		}
		if _, ok := state.Nodes[probe.NodeID]; !ok {
			c.reference("probe_without_node", "probe references a missing node", probe.ID)
		}
		lease, ok := state.Leases[probe.LeaseID]
		if !ok {
			c.reference("probe_without_lease", "probe references a missing lease", probe.ID)
		} else {
			if lease.PlanID != probe.PlanID {
				c.reference("probe_plan_mismatch", "probe plan does not match its lease", probe.ID)
			}
			if lease.NodeID != probe.NodeID {
				c.reference("probe_node_mismatch", "probe node does not match its lease", probe.ID)
			}
			if lease.State != domain.LeaseReported {
				c.summary("lease_probe_state", "a lease carrying a probe must be reported", probe.ID)
			}
			if lease.ProbeID != probe.ID {
				c.reference("probe_backreference", "lease does not point back at this probe", probe.ID)
			}
			if probe.StoredAt.Before(lease.ClaimedAt) {
				c.format("timestamp_order", "probe cannot predate its lease claim", probe.ID)
			}
			if owner, exists := leaseProbes[probe.LeaseID]; exists {
				c.reference("multiple_probes_for_lease", "a lease can carry at most one probe", owner+" / "+probe.ID)
			} else {
				leaseProbes[probe.LeaseID] = probe.ID
			}
		}
		// Fingerprints can be recomputed entirely from the stored probe and
		// lease data, so tampering is detectable offline.
		if lease, ok := state.Leases[probe.LeaseID]; ok {
			input := domain.ProbeInput{
				RequestKey:     probe.RequestKey,
				Success:        probe.Success,
				ObservedSerial: probe.ObservedSerial,
				LatencyMS:      probe.LatencyMS,
				ObservedAt:     probe.ObservedAt,
			}
			if want := domain.ProbeFingerprint(lease.ID, input); want != probe.PayloadFingerprint {
				c.summary("probe_fingerprint", "payload_fingerprint does not match the stored probe payload", probe.ID)
			}
		}
	}
}

func (c *validationContext) validateAssessments() {
	state := c.state
	for key, assessment := range state.Assessments {
		if key != assessment.ID {
			c.format("map_key_mismatch", "assessments map key does not match assessment id", key)
		}
		if !c.validateID(assessment.ID, "asm_") {
			c.format("invalid_id", "assessment id must be generated by the service", key)
		}
		if !validRequestKey(assessment.RequestKey) {
			c.format("invalid_request_key", "request_key must contain 8 to 64 letters, digits, hyphens or underscores", assessment.ID)
		}
		switch assessment.Verdict {
		case domain.VerdictConsistent, domain.VerdictReviewRequired:
		default:
			c.format("invalid_verdict", "verdict must be consistent or review_required", assessment.ID)
		}
		if assessment.CreatedAt.IsZero() {
			c.format("missing_timestamp", "created_at is required", assessment.ID)
		}
		plan, ok := state.Plans[assessment.PlanID]
		if !ok {
			c.reference("assessment_without_plan", "assessment references a missing plan", assessment.ID)
			continue
		}
		if plan.State == domain.PlanDraft {
			c.format("assessment_in_draft_plan", "assessments can exist only on active or completed plans", assessment.ID)
		}
		revision, ok := state.Revisions[assessment.RevisionID]
		if !ok {
			c.reference("assessment_without_revision", "assessment references a missing revision", assessment.ID)
			continue
		}
		if revision.PlanID != assessment.PlanID {
			c.reference("assessment_revision_plan_mismatch", "assessment revision belongs to another plan", assessment.ID)
		}
		for _, reason := range assessment.Reasons {
			switch reason {
			case "no_probes", "node_not_observed", "serial_mismatch",
				"success_ratio_below_minimum", "latency_limit_exceeded":
			default:
				c.format("unknown_reason", "assessment contains an unknown reason code", assessment.ID)
			}
		}
		// Recompute the deterministic verdict from the same inputs the
		// running service uses and require an exact summary match.
		probes := make([]domain.Probe, 0)
		for _, probe := range state.Probes {
			if probe.PlanID == assessment.PlanID {
				probes = append(probes, probe)
			}
		}
		expected := domain.BuildAssessment(assessment.ID, plan, revision, probes, assessment.CreatedAt)
		expected.RequestKey = assessment.RequestKey
		if !reasonsEqual(expected.Reasons, assessment.Reasons) {
			c.summary("assessment_reasons", "assessment reasons do not match recomputation", assessment.ID)
		}
		if expected.Verdict != assessment.Verdict {
			c.summary("assessment_verdict", "verdict does not match recomputation", assessment.ID)
		}
		if expected.ProbeCount != assessment.ProbeCount {
			c.summary("assessment_probe_count", "probe_count does not match recomputation", assessment.ID)
		}
		if expected.SuccessCount != assessment.SuccessCount {
			c.summary("assessment_success_count", "success_count does not match recomputation", assessment.ID)
		}
		if expected.SuccessRatio != assessment.SuccessRatio {
			c.summary("assessment_success_ratio", "success_ratio does not match recomputation", assessment.ID)
		}
		if expected.MaximumLatencyMS != assessment.MaximumLatencyMS {
			c.summary("assessment_max_latency", "maximum_latency_ms does not match recomputation", assessment.ID)
		}
	}
}

func reasonsEqual(a, b []string) bool {
	if len(a) != len(b) {
		return false
	}
	set := make(map[string]struct{}, len(a))
	for _, reason := range a {
		set[reason] = struct{}{}
	}
	for _, reason := range b {
		if _, ok := set[reason]; !ok {
			return false
		}
	}
	return true
}

func (c *validationContext) validateAudit() {
	state := c.state
	seen := make(map[string]struct{}, len(state.AuditEvents))
	for _, event := range state.AuditEvents {
		if !c.validateID(event.ID, "aud_") {
			c.format("invalid_id", "audit event id must be generated by the service", event.ID)
		}
		if _, duplicate := seen[event.ID]; duplicate {
			c.format("duplicate_audit_id", "audit event ids must be unique", event.ID)
		}
		seen[event.ID] = struct{}{}
		if event.EntityType == "" || event.Action == "" || event.At.IsZero() {
			c.format("invalid_audit_event", "entity_type, action and at are required on audit events", event.ID)
		}
		if _, known := knownAuditEntities[event.EntityType]; !known {
			c.format("unknown_audit_entity", "audit event references an unknown entity type", event.ID)
		}
		exists := false
		switch event.EntityType {
		case "plan":
			_, exists = state.Plans[event.EntityID]
		case "revision":
			_, exists = state.Revisions[event.EntityID]
		case "node":
			_, exists = state.Nodes[event.EntityID]
		case "lease":
			_, exists = state.Leases[event.EntityID]
		case "lease_group":
			_, exists = state.LeaseGroups[event.EntityID]
		case "probe":
			_, exists = state.Probes[event.EntityID]
		case "assessment":
			_, exists = state.Assessments[event.EntityID]
		}
		if !exists {
			c.reference("audit_without_entity", "audit event references a missing entity", event.ID)
		}
	}
	if state.Revision == 0 && entityCount(state) > 0 {
		c.format("invalid_state_revision", "state revision must be at least 1 when entities exist", "")
	}
	if state.Revision > 0 && len(state.AuditEvents) > int(state.Revision) {
		c.summary("audit_count", "audit event count cannot exceed the state revision", "")
	}
}

func entityCount(state *domain.State) int {
	return len(state.Plans) + len(state.Revisions) + len(state.Nodes) +
		len(state.Leases) + len(state.LeaseGroups) + len(state.Probes) +
		len(state.Assessments)
}

// validateIndexes verifies the two idempotency indexes are complete, unique
// and consistent with the lease groups and assessments they point at.
func (c *validationContext) validateIndexes() {
	state := c.state

	leaseIndexGroups := make(map[string]string)
	for key, groupID := range state.LeaseRequestKeys {
		planID, requestKey, ok := strings.Cut(key, "\x00")
		if !ok || planID == "" || !validRequestKey(requestKey) {
			c.index("invalid_index_key", "lease request index key must be plan_id + NUL + request_key", key)
		}
		group, exists := state.LeaseGroups[groupID]
		if !exists {
			c.index("index_without_group", "lease request index points at a missing lease group", key)
			continue
		}
		if group.PlanID != planID || group.RequestKey != requestKey {
			c.index("index_group_mismatch", "lease request index does not match its lease group", key)
		}
		identity := group.PlanID + "\x00" + group.RequestKey
		if owner, duplicate := leaseIndexGroups[identity]; duplicate {
			c.index("duplicate_request_key", "two lease groups share one plan request key", owner+" / "+group.ID)
		} else {
			leaseIndexGroups[identity] = group.ID
		}
	}
	for groupID, group := range state.LeaseGroups {
		key := group.PlanID + "\x00" + group.RequestKey
		if indexed, ok := state.LeaseRequestKeys[key]; !ok {
			c.index("missing_index_entry", "lease group is not reachable through the request key index", groupID)
		} else if indexed != group.ID {
			c.index("index_target_mismatch", "lease request index points at another group", groupID)
		}
	}

	assessmentIndexAssessments := make(map[string]string)
	for key, assessmentID := range state.AssessmentRequestKeys {
		planID, requestKey, ok := strings.Cut(key, "\x00")
		if !ok || planID == "" || !validRequestKey(requestKey) {
			c.index("invalid_index_key", "assessment request index key must be plan_id + NUL + request_key", key)
		}
		assessment, exists := state.Assessments[assessmentID]
		if !exists {
			c.index("index_without_assessment", "assessment request index points at a missing assessment", key)
			continue
		}
		if assessment.PlanID != planID || assessment.RequestKey != requestKey {
			c.index("index_assessment_mismatch", "assessment request index does not match its assessment", key)
		}
		identity := assessment.PlanID + "\x00" + assessment.RequestKey
		if owner, duplicate := assessmentIndexAssessments[identity]; duplicate {
			c.index("duplicate_request_key", "two assessments share one plan request key", owner+" / "+assessment.ID)
		} else {
			assessmentIndexAssessments[identity] = assessment.ID
		}
	}
	for assessmentID, assessment := range state.Assessments {
		key := assessment.PlanID + "\x00" + assessment.RequestKey
		if indexed, ok := state.AssessmentRequestKeys[key]; !ok {
			c.index("missing_index_entry", "assessment is not reachable through the request key index", assessmentID)
		} else if indexed != assessment.ID {
			c.index("index_target_mismatch", "assessment request index points at another assessment", assessmentID)
		}
	}
}

func (c *validationContext) validateGlobalCoherence() {
	// Cross-entity timestamp ordering: no child entity may predate its plan.
	state := c.state
	for _, probe := range state.Probes {
		if plan, ok := state.Plans[probe.PlanID]; ok && probe.StoredAt.Before(plan.CreatedAt) {
			c.format("timestamp_order", "probe cannot predate its plan", probe.ID)
		}
	}
	for _, group := range state.LeaseGroups {
		if plan, ok := state.Plans[group.PlanID]; ok && group.CreatedAt.Before(plan.CreatedAt) {
			c.format("timestamp_order", "lease group cannot predate its plan", group.ID)
		}
	}
	for _, assessment := range state.Assessments {
		if plan, ok := state.Plans[assessment.PlanID]; ok && assessment.CreatedAt.Before(plan.CreatedAt) {
			c.format("timestamp_order", "assessment cannot predate its plan", assessment.ID)
		}
	}
}

func validRequestKey(value string) bool {
	count := utf8.RuneCountInString(value)
	if count < domain.MinRequestKeyRunes || count > domain.MaxRequestKeyRunes {
		return false
	}
	for _, r := range value {
		if r >= 'a' && r <= 'z' || r >= 'A' && r <= 'Z' || r >= '0' && r <= '9' {
			continue
		}
		if r == '-' || r == '_' {
			continue
		}
		return false
	}
	return true
}

func validateCanonical(value string) error {
	if value == "" {
		return errInvalidName("is required")
	}
	if len(value) > domain.MaxZoneRunes {
		return errInvalidName("is too long")
	}
	for _, label := range strings.Split(value, ".") {
		if len(label) < 1 || len(label) > 63 {
			return errInvalidName("contains an invalid label length")
		}
		if label[0] == '-' || label[len(label)-1] == '-' {
			return errInvalidName("labels cannot start or end with a hyphen")
		}
		for _, r := range label {
			if r >= 'a' && r <= 'z' || r >= '0' && r <= '9' || r == '-' || r == '_' {
				continue
			}
			return errInvalidName("contains unsupported characters")
		}
	}
	return nil
}

type nameValidationError string

func (e nameValidationError) Error() string { return string(e) }

func errInvalidName(message string) error { return nameValidationError(message) }
